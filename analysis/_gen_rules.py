import io, re
src = io.open(r'D:\projects\cyber-reverse\analysis\pe_strings.txt', encoding='utf-8', errors='replace').read().splitlines()
def text_at(n):
    return src[n-1][12:]

rules = [text_at(n).rstrip() for n in range(158472, 158483)]
assert all(r.lstrip().startswith('{ match:') for r in rules), 'a rule line did not parse'
