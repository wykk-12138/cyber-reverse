m = re.match(r"\s*const CSS_DECL = (\[.*\])\s*;?\s*$", css_line)
assert m, css_line[:80]
css_list = m.group(1)

def block(name, doc, body):
    pad = '        '
    lines = [pad + l.lstrip() if False else pad + l for l in body.split('\n')]
