"""Emit the recovered GraphQL operations as a C# constants file. (R790)

R789 transcribed AddToCart by hand, and hand-transcription of a 536-character string is a known way to lose a
character without the compiler noticing. These two operations are 1,995 and 2,249 characters. Copying them into C# by
hand would be four thousand characters of risk for no benefit.

So the constants are generated from the evidence file instead. That makes the relationship explicit: the source is
analysis/warhammer_graphql.txt, which R788 recovered from the image's string pool, and the generated file is a build
artifact of it rather than an independent transcription. Regenerating is one command, and a diff shows any drift.

Naming: four operations declare their own name in the text. The other two are anonymous -- "mutation (" with no name
-- so their names are taken from the root field they call, updateShippingAddress and updateShippingRate. That is a
naming choice, and the file says so; it is not a claim about what the image calls them.

Why not an existing tool: this is a two-minute generator specific to one evidence file's layout, and nothing in
seep-reverse-lab or rea emits C# source from recovered text.
"""

import io
import re

SRC = r"D:\projects\cyber-reverse\analysis\warhammer_graphql.txt"
OUT = r"D:\projects\cyber-reverse\replica\src\Cybersole.Stores\Flows\WarhammerQueries.g.cs"

HEADER = '''// <auto-generated>
// Generated by analysis/emit_warhammer_queries.py from analysis/warhammer_graphql.txt.
// Do not edit by hand: re-run the generator, and the diff will show what moved.
//
// The source file holds operations recovered from the image's string pool in R788. Two of the six are anonymous
// GraphQL mutations; their constant names come from the root field each calls, which is a naming choice rather than
// something the image states.
// </auto-generated>

namespace Cybersole.Stores.Flows;

/// <summary>Warhammer's GraphQL operations, verbatim from the image.</summary>
public static class WarhammerQueries
{
'''


def name_for(block):
    """Prefer the declared operation name; fall back to the root field the mutation calls."""
    first = block.split("\n", 1)[0].strip()
    named = re.match(r"^(?:mutation|query)\s+([A-Za-z_][A-Za-z0-9_]*)", first)
    if named:
        return named.group(1), "declared"
    root = re.search(r"^\s{2}([a-z][A-Za-z0-9_]*)\s*\(", block, re.MULTILINE)
    if root:
        field = root.group(1)
        return field[0].upper() + field[1:], "root-field"
    return None, None


def csharp_literal(text):
    """Verbatim string literal: doubled quotes, no escape processing."""
    return '@"' + text.replace('"', '""') + '"'


def main():
    raw = io.open(SRC, encoding="utf-8").read()

    # blocks are separated by the "---" rule the extractor writes
    blocks = []
    for chunk in raw.split("\n---\n"):
        body = [l for l in chunk.splitlines() if not l.startswith("#")]
        text = "\n".join(body).strip()
        if text.startswith(("mutation", "query")) and len(text) > 100:
            blocks.append(text)

    parts = [HEADER]
    emitted = []
    for text in blocks:
        name, source = name_for(text)
        if not name:
            print("  skipping an operation with no derivable name")
            continue
        emitted.append((name, source, len(text)))
        parts.append("    /// <summary>%d characters, name from %s.</summary>\n" % (len(text), source))
        parts.append("    public const string %s = %s;\n\n" % (name, csharp_literal(text)))
    parts.append("}\n")

    io.open(OUT, "w", encoding="utf-8", newline="\n").write("".join(parts))
    print("  wrote %s" % OUT)
    for name, source, size in emitted:
        print("    %-28s %5d chars  (%s)" % (name, size, source))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
