#!/usr/bin/env python3
"""Check every session-variable key name against the image, in two stages.

Why this exists (AGENTS.md §1 rule 2): `endpoint-provenance.py` does this for endpoint
constants and `locale_from_binary.py` does it for locale keys. Neither covers the strings used
as `Vars[...]` keys, and those are where R956 and R1008 both found a name that compiled and
read correctly but was never in the artifact. A single find per round will keep missing them;
this asks the whole set once.

Two stages, because the cheap source is a sample and the exact source is slow:
  stage 1  analysis/pe_strings.txt is a SAMPLE (180,228 of 324,895), so a hit proves presence
           but a miss proves nothing (AGENTS.md §2.7b). Hits are settled here.
  stage 2  whatever stage 1 missed is asked of the IDB itself with analysis/ida.py str, which
           is authoritative in both directions. That is a few dozen keys rather than 326, so the
           per-query cost is acceptable.

Output: analysis/VARS_KEY_PROVENANCE.md, with counts and one row per key that stage 2 had to ask.
"""

import io
import json
import os
import re
import subprocess
import sys

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), ".."))
SRC = os.path.join(ROOT, "replica", "src")
POOL = os.path.join(ROOT, "analysis", "pe_strings.txt")
OUT = os.path.join(ROOT, "analysis", "VARS_KEY_PROVENANCE.md")
IDA = os.path.join(ROOT, "analysis", "ida.py")

PAT = re.compile(r'(?:Vars\[|Vars\.TryGetValue\(|Vars\.GetValueOrDefault\(|Vars\.ContainsKey\()\s*"([^"]+)"')


def collect():
    keys = {}
    for dp, _d, fns in os.walk(SRC):
        if os.sep + "obj" in dp or os.sep + "bin" in dp:
            continue
        for fn in fns:
            if not fn.endswith(".cs"):
                continue
            p = os.path.join(dp, fn)
            for n, line in enumerate(io.open(p, encoding="utf-8", errors="replace").read().splitlines(), 1):
                for m in PAT.finditer(line):
                    keys.setdefault(m.group(1), "%s:%d" % (
                        os.path.relpath(p, ROOT).replace(os.sep, "/"), n))
    return keys


def stage1(keys):
    """A hit in the sample is proof; a miss is not. Returns the keys the sample settled."""
    blob = io.open(POOL, encoding="utf-8", errors="replace").read()
    hit, miss = [], []
    for key in keys:
        # the pool holds one string per line, so require the key to be a line of its own or a
        # whitespace-delimited token; a bare substring match would call "home" present because
        # "homepage" exists.
        if ("\n" + key + "\n") in blob or blob.startswith(key + "\n"):
            hit.append(key)
        else:
            miss.append(key)
    return hit, miss


def stage2(miss):
    """Ask the IDB. Authoritative both ways, which is why only the misses go here."""
    settled = {}
    for key in miss:
        p = subprocess.run([sys.executable, IDA, "str", key], capture_output=True, text=True,
                           encoding="utf-8", errors="replace")
        try:
            settled[key] = json.loads(p.stdout).get("n", -1)
        except Exception:
            settled[key] = -1
    return settled


def main():
    keys = collect()
    hit, miss = stage1(keys)
    print("distinct keys: %d   settled by the sample: %d   to ask the IDB: %d"
          % (len(keys), len(hit), len(miss)))

    settled = stage2(miss) if miss else {}
    absent = sorted(k for k, n in settled.items() if n == 0)
    unknown = sorted(k for k, n in settled.items() if n < 0)
    present = sorted(k for k, n in settled.items() if n > 0)

    lines = ["# Session-variable keys against the image", "",
             "Generated by `python analysis/vars_key_provenance.py`. Do not hand-edit.", "",
             "| | count |", "|---|---|",
             "| distinct keys | %d |" % len(keys),
             "| present in the image (sample or IDB) | %d |" % (len(hit) + len(present)),
             "| **absent from the image** | **%d** |" % len(absent),
             "| unresolved | %d |" % len(unknown), ""]

    if present:
        lines += ["## Found by the IDB after the sample missed them: %d" % len(present), "",
                  "These are present, so the sample's miss was its own limit and not the image's.", ""]
        for k in present:
            lines.append("- `%s` (%d) — %s" % (k, settled[k], keys[k]))
        lines.append("")

    lines += ["## Absent from the image: %d" % len(absent), "",
              "Each is a key name this workspace chose. R956 found one and R1008 found another by hand;"
              " this is the whole set asked at once.", ""]
    for k in absent:
        lines.append("- `%s` — first use %s" % (k, keys[k]))
    lines.append("")

    if unknown:
        lines += ["## Unresolved: %d" % len(unknown), "",
                  "The IDB did not answer for these, so nothing is claimed either way.", ""]
        for k in unknown:
            lines.append("- `%s` — first use %s" % (k, keys[k]))
        lines.append("")

    io.open(OUT, "w", encoding="utf-8", newline="\n").write("\n".join(lines) + "\n")
    print("absent: %d   present-after-IDB: %d   unresolved: %d" % (len(absent), len(present), len(unknown)))
    print("wrote %s" % os.path.relpath(OUT, ROOT))
    return 0


if __name__ == "__main__":
    sys.exit(main())
