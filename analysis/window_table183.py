def extract(name):
    """Read the string array assigned to `const NAME = [...]` out of the pool."""
    i = text.find("const " + name + " = [")
    if i < 0:
        raise SystemExit("not found: " + name)
    start = text.index("[", i)
    end = text.index("];", start)
    body = text[start + 1:end]
    return re.findall(r'"((?:[^"\\]|\\.)*)"', body)


