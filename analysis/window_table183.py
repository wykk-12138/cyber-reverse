def cs_array(name, names, per_line=6):
    lines = []
    for i in range(0, len(names), per_line):
        chunk = names[i:i + per_line]
        lines.append("            " + ", ".join('"' + n.replace('"', '\\"') + '"' for n in chunk) + ",")
    return ("        public static readonly string[] " + name + " =\n        {\n"
            + "\n".join(lines) + "\n        };\n")


