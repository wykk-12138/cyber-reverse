    private static readonly Dictionary<long, int> Lookup = BuildLookup();

    private static Dictionary<long, int> BuildLookup()
    {
        var map = new Dictionary<long, int>(Table.Length);
        for (var i = 0; i < Table.Length; i++)
            map[Key(Table[i].Bits, Table[i].Code)] = i;
        return map;
    }

    private static long Key(int bits, uint code) => ((long)bits << 32) | code;

    /// <summary>Decode a Huffman-encoded HPACK string. Returns the prefix decoded so far on bad padding.</summary>
    public static string Decode(ReadOnlySpan<byte> data)
    {
        var sb = new StringBuilder(data.Length);
        var current = 0;
        var bits = 0;

        foreach (var b in data)
        {
            for (var i = 7; i >= 0; i--)
            {
                current = (current << 1) | ((b >> i) & 1);
                bits++;

                if (Lookup.TryGetValue(Key(bits, (uint)current), out var symbol))
                {
                    if (symbol == 256) return sb.ToString(); // EOS
                    sb.Append((char)symbol);
                    current = 0;
                    bits = 0;
                }
                else if (bits > 30)
                {
                    return sb.ToString(); // truncated / invalid padding
                }
            }
        }

        return sb.ToString();
    }
